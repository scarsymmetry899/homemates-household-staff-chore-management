const localeByLanguage: Record<AppLanguage, string> = {
  en: "en-IN",
  hi: "hi-IN",
  te: "te-IN",
  kn: "kn-IN",
  ml: "ml-IN",
};

export function translate(language: AppLanguage, key: string, params: Record<string, string | number> = {}) {
  const template =
    supplementalDictionaries[language][key] ||
    dictionaries[language][key] ||
    supplementalDictionaries.en[key] ||
    dictionaries.en[key] ||
    key;
  return Object.entries(params).reduce(
    (value, [param, replacement]) => value.replaceAll(`{{${param}}}`, String(replacement)),
    template
  );
}

export function localeFor(language: AppLanguage) {
  return localeByLanguage[language] || "en-IN";
}

export function useI18n() {
  const { language } = useAppState();
  return useMemo(
    () => ({
      language,
      locale: localeFor(language),
      t: (key: string, params?: Record<string, string | number>) => translate(language, key, params),
    }),
    [language]
  );
}
